-- 1. Tabela de Colaboradores (Employees)
CREATE TABLE IF NOT EXISTS public.employees (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  document TEXT,
  email TEXT,
  phone TEXT,
  department TEXT NOT NULL DEFAULT 'Operações',
  position TEXT NOT NULL DEFAULT 'Colaborador',
  pin TEXT DEFAULT '1234',
  photo_url TEXT,
  face_descriptor TEXT,
  fingerprint_id TEXT,
  work_schedule_type TEXT DEFAULT 'mon_fri',
  work_days TEXT DEFAULT '[1,2,3,4,5]',
  weekly_day_off TEXT DEFAULT 'Sábado e Domingo',
  start_time TEXT DEFAULT '08:00',
  end_time TEXT DEFAULT '17:00',
  break_start TEXT DEFAULT '12:00',
  break_end TEXT DEFAULT '13:00',
  tolerance_minutes INTEGER DEFAULT 15,
  is_active INTEGER DEFAULT 1,
  created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW())
);

-- 2. Tabela de Batidas de Ponto (Attendance Records)
CREATE TABLE IF NOT EXISTS public.attendance_records (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id BIGINT REFERENCES public.employees(id) ON DELETE CASCADE,
  timestamp TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW()),
  type TEXT NOT NULL,
  verification_method TEXT NOT NULL,
  status TEXT NOT NULL,
  delay_minutes INTEGER DEFAULT 0,
  photo_snapshot TEXT,
  notes TEXT,
  created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW())
);

CREATE INDEX IF NOT EXISTS idx_attendance_employee ON public.attendance_records(employee_id);
CREATE INDEX IF NOT EXISTS idx_attendance_timestamp ON public.attendance_records(timestamp);

-- 3. Tabela de Configurações (Settings)
CREATE TABLE IF NOT EXISTS public.settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

